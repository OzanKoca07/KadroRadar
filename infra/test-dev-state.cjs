const root=path.resolve(__dirname,'..'),runId='a'.repeat(32),created='2026-10-31T09:00:00.000Z';
const state={version:2,root,runId,pid:100,startedAt:created,ownerCreated:created,services:[{name:'api',pid:101,created}]};
